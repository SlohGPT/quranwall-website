/**
 * Rewrites the "Guides" section of public/llms.txt from src/data/blogPosts.json, between the two marker lines.
 * Everything outside the markers (the curated header and key facts) is left alone.
 * Runs first in `npm run build`; idempotent, so the committed file only changes when the post data does.
 *
 *   node scripts/gen-llms-guides.mjs          rewrite public/llms.txt
 *   node scripts/gen-llms-guides.mjs --check  exit 1 if public/llms.txt is out of date (no write)
 */
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://quranwall.com';
const START = '<!-- guides:start (generated by scripts/gen-llms-guides.mjs from src/data/blogPosts.json; do not edit by hand) -->';
const END = '<!-- guides:end -->';

// Same order and headings as src/lib/clusters.ts (kept as plain data here so the build step needs no TS).
const CLUSTERS = [
  ['daily-quran-lock-screen', 'Daily Quran on your Lock Screen'],
  ['dua-and-dhikr-iphone', 'Dhikr and dua on iPhone'],
  ['muslim-productivity-iphone', 'Muslim routines on iPhone'],
  ['quran-study-tools-ios', 'Quran study on iPhone'],
  ['muslim-app-comparisons', 'Muslim app comparisons'],
];

const posts = JSON.parse(readFileSync(join(root, 'src/data/blogPosts.json'), 'utf8')).filter((p) => p.isPublished !== false);

/** One line from the post description. llms.txt names one minimum iOS (facts.json), so iOS-version sentences are dropped. */
function summary(description) {
  const sentences = description
    .replace(/\s*\([^)]*\biOS\s?\d[^)]*\)/g, '')
    .split(/(?<=[.!?])\s+/)
    .filter((s) => !/\biOS\s?\d/.test(s));
  return (sentences.join(' ') || description).replace(/\s+/g, ' ').trim();
}

const lines = ['## Guides', ''];
const known = new Set(CLUSTERS.map(([id]) => id));
for (const p of posts) if (!known.has(p.cluster)) throw new Error(`gen-llms-guides: unknown cluster "${p.cluster}" (post ${p.slug}); add it to CLUSTERS`);
for (const [id, heading] of CLUSTERS) {
  const group = posts.filter((p) => p.cluster === id);
  if (!group.length) continue;
  lines.push(`### ${heading}`, '');
  for (const p of group) lines.push(`- ${p.title} — ${summary(p.description)} — ${SITE}/blog/${p.slug}`);
  lines.push('');
}
const block = `${START}\n${lines.join('\n').trimEnd()}\n${END}`;

const file = join(root, 'public/llms.txt');
const text = readFileSync(file, 'utf8');
const a = text.indexOf(START);
const b = text.indexOf(END);
let next;
if (a >= 0 && b > a) next = text.slice(0, a) + block + text.slice(b + END.length);
else {
  const at = text.indexOf('## Last updated');
  if (at < 0) throw new Error('gen-llms-guides: no markers and no "## Last updated" heading to insert before');
  next = text.slice(0, at) + block + '\n\n' + text.slice(at);
}

if (process.argv.includes('--check')) {
  if (next !== text) { console.error('public/llms.txt guides section is out of date: run node scripts/gen-llms-guides.mjs'); process.exit(1); }
  console.log('public/llms.txt guides section is up to date');
} else {
  if (next !== text) writeFileSync(file, next);
  console.log(`llms.txt guides: ${posts.length} posts in ${CLUSTERS.filter(([id]) => posts.some((p) => p.cluster === id)).length} clusters${next !== text ? ' (rewritten)' : ' (unchanged)'}`);
}
